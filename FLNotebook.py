def df_to_latex(df, caption, label, col_format=None):
    """Convert DataFrame to a LaTeX table string."""
    n_cols = len(df.columns)
    if col_format is None:
        col_format = 'l' + 'c' * (n_cols - 1)
    lines = [
        r'\begin{table}[htbp]',
        r'\centering',
        r'\small',
        f'\\caption{{{caption}}}',
        f'\\label{{{label}}}',
        f'\\begin{{tabular}}{{{col_format}}}',
        r'\hline',
        ' & '.join(f'\\textbf{{{c}}}' for c in df.columns) + r' \\',
        r'\hline',
    ]
    for _, row in df.iterrows():
        lines.append(' & '.join(str(v) for v in row.values) + r' \\')
    lines += [r'\hline', r'\end{tabular}', r'\end{table}']
    return '\n'.join(lines)


# ── FIX-5: robust loaders ─────────────────────────────────────
def _load_df(in_memory_obj, csv_path, name):
    """Return in-memory DataFrame if valid, else try CSV, else empty."""
    if (in_memory_obj is not None
            and isinstance(in_memory_obj, pd.DataFrame)
            and len(in_memory_obj) > 0):
        print(f'  ✓ {name}: using in-memory ({len(in_memory_obj)} rows)')
        return in_memory_obj
    if os.path.exists(csv_path):
        df = pd.read_csv(csv_path)
        print(f'  ✓ {name}: loaded from disk ({len(df)} rows)')
        return df
    print(f'  ⚠ {name}: not found in memory or at {csv_path}')
    return pd.DataFrame()


def _load_conv(in_memory_obj, pkl_path, name):
    """Return in-memory dict if valid, else try pickle, else {}."""
    if (in_memory_obj is not None
            and isinstance(in_memory_obj, dict)
            and len(in_memory_obj) > 0):
        print(f'  ✓ {name}: using in-memory ({len(in_memory_obj)} keys)')
        return in_memory_obj
    if os.path.exists(pkl_path):
        with open(pkl_path, 'rb') as fh:
            d = pickle.load(fh)
        print(f'  ✓ {name}: loaded from disk ({len(d)} keys)')
        return d
    print(f'  ⚠ {name}: not found in memory or at {pkl_path}')
    return {}


