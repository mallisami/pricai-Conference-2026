# ── MLP Model ────────────────────────────────────────────────────
class GPUMLP(nn.Module):
    def __init__(self, in_dim, hidden, n_classes=2, dropout=0.1):
        super().__init__()
        layers, prev = [], in_dim
        for h in hidden:
            layers += [
                nn.Linear(prev, h),
                nn.LayerNorm(h),
                nn.ReLU(),
                nn.Dropout(dropout)
            ]
            prev = h
        layers.append(nn.Linear(prev, n_classes))
        self.net = nn.Sequential(*layers)
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.kaiming_normal_(m.weight)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)

    def forward(self, x):
        return self.net(x)


def make_model():
    """Create a fresh GPUMLP on DEVICE."""
    return GPUMLP(N_FEATURES, HIDDEN).to(DEVICE)


# ── Weight helpers ────────────────────────────────────────────────
def get_weights(model):
    """Flatten all parameters into a single vector."""
    return torch.cat([p.data.view(-1) for p in model.parameters()])


def set_weights(model, vec):
    """Load a flat vector back into model parameters."""
    offset = 0
    for p in model.parameters():
        n = p.numel()
        p.data.copy_(vec[offset:offset + n].view(p.shape))
        offset += n


# ── Inference ─────────────────────────────────────────────────────
def predict(model, X_t):
    """Run inference, return numpy predictions."""
    model.eval()
    with torch.no_grad():
        return model(X_t).argmax(dim=1).cpu().numpy()


# ── Gradient clipping on weight vectors ──────────────────────────
def clip_weights(weights, clip_value):
    """Median-relative clipping (consistent with Cell 7)."""
    norms = torch.tensor([w.norm().item() for w in weights])
    med   = norms.median().item()

    clipped = []
    for w, n in zip(weights, norms):
        scale = min(1.0, (med * clip_value) / (n.item() + 1e-8))
        clipped.append(w * scale)

    return clipped


# ── Local training ────────────────────────────────────────────────
def train_local(X_np, y_np, global_weights=None, seed=42, n_epochs=None):
    """
    Train one local MLP.
    Returns (model, n_samples) or (None, 0) if data degenerate.
    """
    if X_np is None or len(X_np) < 10 or len(np.unique(y_np)) < 2:
        return None, 0

    if n_epochs is None:
        n_epochs = EPOCHS

    torch.manual_seed(seed)

    model = make_model()
    if global_weights is not None:
        set_weights(model, global_weights.to(DEVICE))

    X_t = torch.from_numpy(X_np.astype(np.float32)).to(DEVICE)
    y_t = torch.from_numpy(y_np.astype(np.int64)).to(DEVICE)

    loader    = DataLoader(TensorDataset(X_t, y_t),
                           batch_size=BATCH_SIZE, shuffle=True, drop_last=False)
    optimizer = optim.Adam(model.parameters(), lr=LR, weight_decay=WEIGHT_DECAY)
    criterion = nn.CrossEntropyLoss()

    model.train()
    for _ in range(n_epochs):
        for xb, yb in loader:
            optimizer.zero_grad()
            loss = criterion(model(xb), yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), CLIP_VALUE)
            optimizer.step()

    return model, len(X_np)


# ── Dirichlet non-IID split — single function used everywhere ────
def dirichlet_split(df_pool, n_nodes, alpha, seed, label_col='label_2'):
    """
    Split df_pool into n_nodes DataFrames using Dirichlet distribution.
    Single definition — used by main loop, ablation, and UNSW cell.
    """
    rng = np.random.default_rng(seed)
    tmp = df_pool.reset_index(drop=True)
    splits = [[] for _ in range(n_nodes)]

    for lbl in tmp[label_col].unique():
        idxs = tmp.index[tmp[label_col] == lbl].to_numpy().copy()
        rng.shuffle(idxs)
        props  = rng.dirichlet([alpha] * n_nodes)
        counts = np.floor(props * len(idxs)).astype(int)
        # fix rounding
        while counts.sum() < len(idxs):
            counts[rng.integers(0, n_nodes)] += 1
        while counts.sum() > len(idxs):
            j = rng.integers(0, n_nodes)
            if counts[j] > 0:
                counts[j] -= 1
        s = 0
        for nid, cnt in enumerate(counts):
            splits[nid].extend(idxs[s:s + cnt].tolist())
            s += cnt

    out = []
    for nid, idxs in enumerate(splits):
        node_df = tmp.loc[idxs].copy()
        # ensure minimum samples and class diversity
        if len(node_df) < 20 or node_df[label_col].nunique() < 2:
            other = tmp[~tmp.index.isin(idxs)]
            need  = max(0, 20 - len(node_df))
            if need > 0 and len(other) > 0:
                node_df = pd.concat([
                    node_df,
                    other.sample(n=min(need, len(other)), random_state=seed + nid)
                ])
            # add diversity if only one class
            if node_df[label_col].nunique() < 2 and len(other) > 0:
                diff = other[other[label_col] != node_df[label_col].iloc[0]]
                if len(diff) > 0:
                    node_df = pd.concat([
                        node_df,
                        diff.sample(n=min(5, len(diff)), random_state=seed + nid + 100)
                    ])
        out.append(node_df.reset_index(drop=True))

    return out


