"                torch.from_numpy(X_np).to(device),\n"
"                torch.from_numpy(y_np).to(device))\n"
"            dl  = DataLoader(ds, batch_size=BATCH_SIZE, shuffle=True, drop_last=False)\n"
"            opt  = torch.optim.Adam(m.parameters(), lr=LR, weight_decay=WEIGHT_DECAY)\n"
"            crit = nn.CrossEntropyLoss()\n"
"            m.train()\n"
"            for _ in range(n_epochs):\n"
"                for xb, yb in dl:\n"
"                    opt.zero_grad()\n"
"                    loss = crit(m(xb), yb)\n"
"                    loss.backward()\n"
"                    nn.utils.clip_grad_norm_(m.parameters(), CLIP_VALUE)\n"
"                    opt.step()\n"
"            return m, len(X_np)\n"
"\n"
"        def agg_fedavg(ws, cs):\n"
"            total   = sum(cs)\n"
"            stacked = torch.stack(ws)\n"
"            wts     = torch.tensor([c / total for c in cs], dtype=torch.float32)\n"
"            return (stacked * wts.view(-1, 1)).sum(0)\n"
"\n"
"        def agg_trimmed(ws, trim=0.2):\n"
"            arr = torch.stack(ws)\n"
"            n   = arr.shape[0]\n"
"            k   = max(1, int(n * trim))\n"
"            if 2 * k >= n:\n"
"                return arr.mean(0)\n"
"            return torch.sort(arr, dim=0).values[k:n - k].mean(0)\n"
"\n"
"        def agg_rfa(ws, eps=1e-6, max_iter=50):\n"
"            arr = torch.stack(ws)\n"
"            if arr.shape[0] <= 2:\n"
"                return arr.mean(0)\n"
"            y = arr.median(0).values.clone()\n"
"            for _ in range(max_iter):\n"
"                d  = (arr - y).norm(dim=1).clamp(min=eps)\n"
"                wi = 1.0 / d\n"
"                wi = wi / wi.sum()\n"
"                yn = (wi.unsqueeze(1) * arr).sum(0)\n"
"                if (yn - y).norm() < eps:\n"
"                    break\n"
"                y = yn\n"
"            return y\n"
"\n"
"        def agg_flame(ws, counts=None):\n"
"            arr = torch.stack(ws)\n"
"            n   = arr.shape[0]\n"
"            if n <= 2:\n"
"                return arr.mean(0)\n"
"            normed   = arr / arr.norm(dim=1, keepdim=True).clamp(min=1e-9)\n"
"            cos_dist = 1.0 - normed @ normed.T\n"
"            med_dist = cos_dist.median(dim=1).values\n"
"            mask     = med_dist <= med_dist.median() * 2.0\n"
"            if mask.sum() == 0:\n"
"                mask = torch.ones(n, dtype=torch.bool, device=arr.device)\n"
"            return arr[mask].mean(0)\n"
"\n"
"        def agg_fldetector(ws, history, threshold=2.0):\n"
"            if len(history) < 2:\n"
"                return torch.stack(ws).mean(0)\n"
"            prev  = history[-1]\n"
"            diffs = [torch.norm(w - prev).item() for w in ws]\n"
"            med   = float(np.median(diffs))\n"
"            std   = float(np.std(diffs)) + 1e-8\n"
"            keep  = [i for i, d in enumerate(diffs)\n"
"                     if abs(d - med) < threshold * std]\n"
"            keep  = keep if keep else list(range(len(ws)))\n"
"            return torch.stack([ws[i] for i in keep]).mean(0)\n"
"\n"
"        def agg_flip(ws, cs=None):\n"
"            arr = torch.stack(ws)\n"
"            if arr.shape[0] <= 2:\n"
"                return arr.mean(0)\n"
"            med      = arr.median(0).values\n"
"            med_norm = med.norm().clamp(min=1e-9)\n"
"            cos      = (arr @ med) / (arr.norm(dim=1).clamp(min=1e-9) * med_norm)\n"
"            threshold = cos.mean() - cos.std()\n"
"            mask = cos >= threshold\n"
"            if mask.sum() == 0:\n"
"                mask = torch.ones(arr.shape[0], dtype=torch.bool, device=arr.device)\n"
"            return arr[mask].mean(0)\n"
"\n"
"        def agg_afa(ws, cs=None):\n"
"            arr = torch.stack(ws)\n"
"            if arr.shape[0] == 1:\n"
"                return arr[0]\n"
"            d     = (arr - arr.mean(0)).norm(dim=1)\n"
"            sg    = d.std().clamp(min=1e-9)\n"
"            trust = torch.exp(-0.5 * (d / sg) ** 2)\n"
"            trust = trust / trust.sum()\n"
"            return (trust.unsqueeze(1) * arr).sum(0)\n"
"\n"
"        def agg_robustfed(ws, cs=None):\n"
"            arr = torch.stack(ws)\n"
"            if arr.shape[0] == 1:\n"
"                return arr[0]\n"
"            med = arr.median(0).values\n"
"            d   = (arr - med).pow(2).sum(dim=1).clamp(min=1e-9)\n"
"            w   = 1.0 / d\n"
"            w   = w / w.sum()\n"
"            return (w.unsqueeze(1) * arr).sum(0)\n"
"\n"
"        def agg_fltrust(ws, cs, server_delta):\n"
"            # NOTE: ws are client UPDATE DELTAS in experiments.\n"
"            sd     = server_delta.to(ws[0].device)\n"
"            scores = [max(0.0, torch.nn.functional.cosine_similarity(\n"
"                          w.unsqueeze(0), sd.unsqueeze(0)).item())\n"
"                      for w in ws]\n"
"            total  = sum(scores)\n"
"            if total < 1e-8:\n"
"                return agg_fedavg(ws, cs)\n"
"            return sum(w * (s / total) for w, s in zip(ws, scores))\n"
"\n"
"        # HAPGUARD — FINAL FIXED (inside worker)\n"
"        # FIX-A: contamination = atk_rate*0.40, clip [0.05,0.30]\n"
"        # FIX-B: RFA (geometric median) replaces cosine-weighted mean\n"
"        # FIX-C: safety floor keeps ceil(N/3) nodes minimum\n"
"        class HAPGUARD:\n"
"            def __init__(self, atk_rate=0.2, seed=42):\n"
"                self.contamination = float(np.clip(atk_rate * 0.40, 0.05, 0.30))\n"
"                self.atk_rate = atk_rate\n"
"                self.seed = seed\n"
"                self.server_ref = None\n"
"\n"
"            def _rfa(self, arr, T=20, eps=1e-6):\n"
"                if arr.shape[0] <= 2:\n"
"                    return arr.mean(0)\n"
"                y = arr.median(0).values.clone()\n"
"                for _ in range(T):\n"
"                    d  = (arr - y).norm(dim=1).clamp(min=eps)\n"
"                    wi = 1.0 / d; wi = wi / wi.sum()\n"
"                    yn = (wi.unsqueeze(1) * arr).sum(0)\n"
"                    if (yn - y).norm() < eps: break\n"
"                    y = yn\n"
"                return y\n"
"\n"
"            def detect(self, node_ids, weights, counts):\n"
"                n = len(weights)\n"
"                if n <= 2:\n"
"                    return torch.stack(weights).mean(0), list(counts), []\n"
"                arr = torch.stack(weights)\n"
"                norms_if      = arr.norm(dim=1, keepdim=True).clamp(min=1e-9)\n"
"                median_norm   = norms_if.median()\n"
"                arr_if        = arr * torch.clamp(median_norm / norms_if, max=1.0)\n"
"                W_np          = arr_if.cpu().numpy()\n"
"                clf = IsolationForest(contamination=self.contamination,\n"
"                                      random_state=self.seed, n_jobs=1)\n"
"                clf.fit(W_np)\n"
"                pred    = clf.predict(W_np)\n"
"                scores  = clf.score_samples(W_np)\n"
"                mask_if = pred == 1\n"
"                min_keep = max(2, int(np.ceil(n / 3)))\n"
"                if mask_if.sum() < min_keep:\n"
"                    top_idx = np.argsort(scores)[-min_keep:]\n"
"                    mask_if = np.zeros(n, dtype=bool)\n"
"                    mask_if[top_idx] = True\n"
"                trusted_weights = arr[mask_if]\n"
"                trusted_counts  = [counts[i] for i in range(n) if mask_if[i]]\n"
"                agg_w = self._rfa(trusted_weights)\n"
"                if torch.isnan(agg_w).any():\n"
"                    agg_w = trusted_weights.mean(0)\n"
"                if torch.isnan(agg_w).any():\n"
"                    agg_w = arr.median(0).values\n"
"                flagged = [nid for i, nid in enumerate(node_ids) if not mask_if[i]]\n"
"                return agg_w, trusted_counts, flagged\n"
"\n"
"        def make_dirichlet_split(df_pool, n_nodes, alpha, seed):\n"
"            rng    = np.random.default_rng(seed)\n"
"            tmp    = df_pool.reset_index(drop=True)\n"
