# ── TAB 2 – Statistical tests (Wilcoxon + BH correction) ──────
# FIX-4: pair samples by seed so wilcoxon works even with 1 seed.
#        With a single seed there is only 1 data point per method →
#        we cannot run a signed-rank test. In that case we report
#        a simple difference and mark the p-value as "n/a (1 seed)".

_stress_data = df_ciciot_raw[
    df_ciciot_raw['Attack_Rate'] == _stress_rate].copy()

# Build paired arrays aligned by Seed
_seeds_avail = sorted(_stress_data['Seed'].unique())
_hg_vals = (
    _stress_data[_stress_data['Method'] == 'HAPGUARD']
    .set_index('Seed')['Accuracy']
    .reindex(_seeds_avail))

baselines_for_stat = [m for m in ACTIVE_METHODS if m != 'HAPGUARD']
pvals_raw, stat_rows = [], []

for baseline in baselines_for_stat:
    _bl_vals = (
        _stress_data[_stress_data['Method'] == baseline]
        .set_index('Seed')['Accuracy']
        .reindex(_seeds_avail))

    # Align (drop seeds missing in either)
    _paired = pd.concat(
        [_hg_vals.rename('hg'), _bl_vals.rename('bl')],
        axis=1).dropna()

    hg_arr = _paired['hg'].values
    bl_arr = _paired['bl'].values
    n      = len(hg_arr)

    row = {
        'Comparison'   : f'HAPGUARD vs {baseline}',
        'HAPGUARD_mean': round(float(hg_arr.mean()), 4) if n > 0 else 'n/a',
        'Baseline_mean': round(float(bl_arr.mean()), 4) if n > 0 else 'n/a',
        'Difference'   : round(float((hg_arr - bl_arr).mean()), 4) if n > 0
                         else 'n/a',
        'W_statistic'  : 'n/a',
        'p_raw'        : 1.0,
        'p_BH'         : 1.0,
        'Significant'  : 'n/a',
        'n_pairs'      : n,
    }

    if n >= 5:             # FIX C: wilcoxon valid from n>=5 (standard in IEEE/Elsevier FL papers)
        try:
            stat, pval = wilcoxon(hg_arr, bl_arr, alternative='greater')
            row['W_statistic'] = round(float(stat), 4)
            row['p_raw']       = round(float(pval), 4)
            row['Significant'] = '?'   # filled after BH
        except Exception as e:
            print(f'    wilcoxon failed for {baseline}: {e}')
    elif n >= 2:           # report difference but flag insufficient pairs
        row['Significant'] = f'n/a ({n} pairs < 5)'
        row['p_raw']       = float('nan')
    else:
        row['Significant'] = f'n/a ({n} pair(s))'
        row['p_raw']       = float('nan')

    pvals_raw.append(row['p_raw'])
    stat_rows.append(row)

# Benjamini-Hochberg on valid p-values only
_valid_mask = [not (isinstance(p, float) and np.isnan(p))
               for p in pvals_raw]
_valid_pvals = [p for p, v in zip(pvals_raw, _valid_mask) if v]

if len(_valid_pvals) >= 1:
    reject_all, pvals_bh_all, _, _ = multipletests(
        _valid_pvals, method='fdr_bh')
    _bh_iter = iter(zip(reject_all, pvals_bh_all))
else:
    _bh_iter = iter([])

for i, row in enumerate(stat_rows):
    if _valid_mask[i]:
        rej, pbh = next(_bh_iter)
        row['p_BH']       = round(float(pbh), 4)
        row['Significant'] = 'Yes*' if rej else 'No'
    else:
        row['p_BH'] = 'n/a'

df_tab2 = pd.DataFrame(stat_rows)
df_tab2.to_csv(RESULTS_DIR + 'tab2_wilcoxon_bh.csv', index=False)

# FIX-10: reset_index so Method column appears in LaTeX output
tex2 = df_to_latex(
    df_tab2.reset_index(drop=True),
    caption=(f'Wilcoxon signed-rank test (HAPGUARD vs each baseline) '
             f'at attack rate = {_stress_rate:.2f}, '
             f'Benjamini-Hochberg corrected. *p < 0.05. '
             f'n_pairs = number of matched seeds.'),
    label='tab:wilcoxon')
