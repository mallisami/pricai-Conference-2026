"\n"
"        all_rows    = []\n"
"        convergence = {}\n"
"        total       = len(jobs)\n"
"\n"
"        for ji, job in enumerate(jobs):\n"
"            seed     = job['seed']\n"
"            atk_rate = job['atk_rate']\n"
"            method   = job['method']\n"
"            random.seed(seed)\n"
"            np.random.seed(seed)\n"
"            torch.manual_seed(seed)\n"
"            if torch.cuda.is_available():\n"
"                torch.cuda.manual_seed_all(seed)\n"
"            conv_key = f'{method}|{atk_rate}'\n"
"            if conv_key not in convergence:\n"
"                convergence[conv_key] = {}\n"
"\n"
"            node_dfs = make_dirichlet_split(\n"
"                df_s, N_NODES, DIRICHLET_ALPHA, seed=seed)\n"
"\n"
"            n_mal   = int(N_NODES * atk_rate)\n"
"            rng_m   = np.random.default_rng(seed)\n"
