            norms_if = arr.norm(dim=1, keepdim=True).clamp(min=1e-9)
            arr_if   = arr * torch.clamp(norms_if.median() / norms_if, max=1.0)
            W_np     = arr_if.cpu().numpy()
            clf = IsolationForest(contamination=self.contamination,
                                  random_state=self.seed, n_jobs=1)
            clf.fit(W_np)
            pred    = clf.predict(W_np)
            scores  = clf.score_samples(W_np)
            mask_if = pred == 1
            min_keep = max(2, int(np.ceil(n / 3)))
            if mask_if.sum() < min_keep:
                top_idx = np.argsort(scores)[-min_keep:]
                mask_if = np.zeros(n, dtype=bool)
                mask_if[top_idx] = True
            trusted_weights = arr[mask_if]
            trusted_counts  = [counts[i] for i in range(n) if mask_if[i]]
            agg_w = self._rfa(trusted_weights)
            if torch.isnan(agg_w).any():
                agg_w = trusted_weights.mean(0)
            if torch.isnan(agg_w).any():
                agg_w = arr.median(0).values
            flagged = [nid for i, nid in enumerate(node_ids) if not mask_if[i]]
            return agg_w, trusted_counts, flagged


